/**
 * Render SPA_EXCLUSIONS as Markdown for the vendored pack.
 *
 * Loads the module rather than parsing the file. A regex over TypeScript would
 * survive exactly until somebody reformats the array, and it would fail by
 * producing a shorter table rather than by erroring — the worst shape of
 * failure for a document whose whole job is to be complete.
 *
 *   node --experimental-strip-types extract-spa-exclusions.mjs <path> > out.md
 */

import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

const source = process.argv[2];
if (!source) {
  console.error('usage: extract-spa-exclusions.mjs <path-to-spa-exclusions.ts>');
  process.exit(1);
}

const module = await import(pathToFileURL(resolve(source)).href);
const entries = module.SPA_EXCLUSIONS;

if (!Array.isArray(entries) || entries.length === 0) {
  console.error('SPA_EXCLUSIONS is missing or empty');
  process.exit(1);
}

const lines = [];
lines.push('# Keeping the manifest out of the catch-all');
lines.push('');
lines.push('**Generated by `scripts/sync-spec.sh` from the validator package.**');
lines.push('Do not edit — the same words ship in the validator CLI (`init');
lines.push('--framework`) and on cabuya.org\'s quickstart, and a hand-edit here');
lines.push('would make this the copy that drifts.');
lines.push('');
lines.push('This is the single most expensive failure in the founding analysis:');
lines.push('four of twenty hosts served their SPA\'s `index.html` at every path, so');
lines.push('the manifest "existed", returned 200, and contained their homepage. The');
lines.push('validator treats `200 + text/html` at a discovery path as **absent**');
lines.push('(the soft-404 rule). Every one of those teams believed they had');
lines.push('published.');
lines.push('');
lines.push('| Framework | Where the file goes |');
lines.push('|---|---|');
for (const entry of entries) {
  lines.push(`| ${entry.label} | ${entry.path ? `\`${entry.path}\`` : '*routing, not placement*'} |`);
}
lines.push('');

for (const entry of entries) {
  lines.push(`### ${entry.label}`);
  lines.push('');
  if (entry.path) {
    lines.push(`\`${entry.path}\``);
    lines.push('');
  }
  lines.push(entry.note.en);
  lines.push('');
  lines.push(`> ${entry.note.es}`);
  lines.push('');
}

lines.push('---');
lines.push('');
lines.push('**Then request the URL.** Placement is not proof. Check the status, the');
lines.push('content type, and whether the body is byte-identical in size to `/` —');
lines.push('that last one is the discriminator, because a catch-all returns the same');
lines.push('shell for every unmatched path.');
lines.push('');
lines.push('```bash');
lines.push('curl -sI https://example.org/.well-known/cabuya.json');
lines.push('curl -s  https://example.org/.well-known/cabuya.json | wc -c');
lines.push('curl -s  https://example.org/ | wc -c');
lines.push('```');

process.stdout.write(lines.join('\n') + '\n');
