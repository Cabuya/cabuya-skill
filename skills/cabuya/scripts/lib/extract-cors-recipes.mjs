/**
 * Render CORS_RECIPES as Markdown for the vendored pack.
 *
 * The same shape as `extract-spa-exclusions.mjs`, and for the same reason: it
 * loads the module rather than parsing it, so a reformat upstream cannot
 * silently produce a shorter table. A guide about what an agent must configure
 * fails worst when it fails by being incomplete.
 *
 * This one exists because `ENV007` is the check a publisher who did everything
 * else right fails first. Two static files are schema-valid and are not L2:
 * the header is a property of the server, and an agent that writes perfect
 * JSON and stops has left its user one silent step short of conforming.
 *
 *   node --experimental-strip-types extract-cors-recipes.mjs <path> > out.md
 */

import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const source = process.argv[2];
if (!source) {
  console.error('usage: extract-cors-recipes.mjs <path-to-cors-recipes.ts>');
  process.exit(1);
}

const module = await import(pathToFileURL(resolve(source)).href);
const entries = module.CORS_RECIPES;

if (!Array.isArray(entries) || entries.length === 0) {
  console.error('CORS_RECIPES is missing or empty');
  process.exit(1);
}

const lines = [];
lines.push('# The one header a feed file cannot carry');
lines.push('');
lines.push('**Generated by `scripts/sync-spec.sh` from the validator package.**');
lines.push('Do not edit — the same words ship in the validator CLI and on');
lines.push("cabuya.org's quickstart, and a hand-edit here would make this the copy");
lines.push('that drifts.');
lines.push('');
lines.push('The specification calls `Access-Control-Allow-Origin: *` **the one');
lines.push('non-obvious MUST** (§3, the feed envelope). It is the check a publisher');
lines.push('who did everything else right fails first: two static files at stable');
lines.push('URLs are schema-valid and are **not** L2, because the header is a');
lines.push('property of the server and no amount of editing JSON produces it.');
lines.push('');
lines.push('Without it, every consumer running in a browser needs a server-side');
lines.push('proxy to read the feed — so the participants with the lowest cost to');
lines.push('build are exactly the ones locked out.');
lines.push('');
lines.push('The validator reports it as **ENV007**.');
lines.push('');
lines.push('| Host | What to add |');
lines.push('|---|---|');
for (const entry of entries) {
  const where = entry.file ? `\`${entry.file}\`` : '*server configuration*';
  lines.push(`| ${entry.label} | ${entry.snippet ? where : '*nothing — see below*'} |`);
}
lines.push('');

for (const entry of entries) {
  lines.push(`### ${entry.label}`);
  lines.push('');
  lines.push(entry.note.en);
  lines.push('');
  if (entry.snippet) {
    if (entry.file) {
      lines.push(`\`${entry.file}\`:`);
      lines.push('');
    }
    lines.push('```');
    lines.push(entry.snippet);
    lines.push('```');
    lines.push('');
  }
}

process.stdout.write(`${lines.join('\n')}\n`);
